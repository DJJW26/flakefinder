#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md for the packages bundled into the GitHub
 * Action (dist/action/index.cjs). The CLI bundle keeps its dependencies
 * external (npm installs them with their own license files), so only the
 * action bundle redistributes third-party code.
 *
 * The package list comes from an esbuild metafile of the same entry point
 * and options tsup uses, so it is exactly what ends up in the bundle.
 * Licenses are read from each package's package.json and LICENSE file in
 * node_modules. Packages without a `license` field are flagged.
 *
 *   node scripts/third-party-notices.mjs           # write THIRD_PARTY_NOTICES.md
 *   node scripts/third-party-notices.mjs --check   # exit 1 if the file is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'THIRD_PARTY_NOTICES.md');

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/action/index.ts'],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node24',
  write: false,
  metafile: true,
  logLevel: 'silent',
  outfile: 'notices-probe.cjs',
});

/** node_modules/<name> or node_modules/@scope/<name> directory of a bundled input. */
function packageDir(input) {
  const parts = input.split('/');
  const i = parts.lastIndexOf('node_modules');
  if (i === -1) return null;
  const n = parts[i + 1]?.startsWith('@') ? 2 : 1;
  return parts.slice(0, i + 1 + n).join('/');
}

const dirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const dir = packageDir(input);
  if (dir) dirs.add(dir);
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

/** Normalise package.json `license` / legacy `licenses` into one SPDX-ish string. */
function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) {
    const types = pkg.licenses.map((l) => (typeof l === 'string' ? l : l?.type)).filter(Boolean);
    if (types.length > 0) return types.join(' OR ');
  }
  return null;
}

const packages = new Map();
for (const dir of dirs) {
  const abs = path.join(root, dir);
  const pkgFile = path.join(abs, 'package.json');
  if (!existsSync(pkgFile)) continue;
  const pkg = JSON.parse(readFileSync(pkgFile, 'utf8'));
  const id = `${pkg.name}@${pkg.version}`;
  if (packages.has(id)) continue;
  const files = readdirSync(abs).filter((f) => LICENSE_FILE.test(f)).sort();
  const texts = files.map((f) =>
    readFileSync(path.join(abs, f), 'utf8').replace(/\r\n?/g, '\n').trim(),
  );
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  packages.set(id, {
    name: pkg.name,
    version: pkg.version,
    license: licenseOf(pkg),
    repository: repo ?? null,
    texts,
  });
}

const list = [...packages.values()].sort((a, b) =>
  a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name),
);
const noLicenseField = list.filter((p) => p.license === null);
const noLicenseText = list.filter((p) => p.texts.length === 0);

const out = [];
out.push('# Third-party notices');
out.push('');
out.push(
  'The GitHub Action bundle (`dist/action/index.cjs`) includes the following',
  'third-party packages. The CLI published to npm does not bundle its',
  'dependencies; npm installs them with their own license files.',
);
out.push('');
out.push(
  'Generated by `node scripts/third-party-notices.mjs` from the packages',
  'esbuild actually bundles. Do not edit by hand; regenerate after',
  'dependency changes.',
);
out.push('');
out.push('| Package | Version | License |');
out.push('|---|---|---|');
for (const p of list) {
  out.push(`| ${p.name} | ${p.version} | ${p.license ?? '**none declared**'} |`);
}
out.push('');
if (noLicenseField.length > 0 || noLicenseText.length > 0) {
  out.push('## Packages needing attention');
  out.push('');
  for (const p of noLicenseField) {
    out.push(
      `- \`${p.name}@${p.version}\` declares **no \`license\` field** in its package.json${
        p.texts.length > 0 ? ' (a license file is included below)' : ' and ships no license file'
      }.`,
    );
  }
  for (const p of noLicenseText) {
    if (p.license === null) continue;
    out.push(
      `- \`${p.name}@${p.version}\` declares \`${p.license}\` but ships no license file; see its repository${
        p.repository ? ` (${p.repository})` : ''
      }.`,
    );
  }
  out.push('');
}
out.push('## License texts');
for (const p of list) {
  out.push('');
  out.push(`### ${p.name}@${p.version}`);
  out.push('');
  out.push(`License: ${p.license ?? 'none declared'}`);
  if (p.repository) out.push(`Repository: ${p.repository}`);
  for (const text of p.texts) {
    out.push('');
    out.push('```text');
    out.push(text.replace(/```/g, '`​``'));
    out.push('```');
  }
}
out.push('');
const content = out.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== content) {
    console.error('THIRD_PARTY_NOTICES.md is stale — run: node scripts/third-party-notices.mjs');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md up to date (${list.length} packages)`);
} else {
  writeFileSync(outFile, content, 'utf8');
  console.log(`wrote THIRD_PARTY_NOTICES.md: ${list.length} packages`);
  for (const p of noLicenseField) console.warn(`  no license field: ${p.name}@${p.version}`);
  for (const p of noLicenseText) {
    if (p.license !== null) console.warn(`  no license file: ${p.name}@${p.version}`);
  }
}
